void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2)
    {
        if (modbus_rx_index < sizeof(modbus_rx_buffer))
        {
            modbus_rx_buffer[modbus_rx_index++] = rx_byte;
        }

        if (modbus_rx_index >= 8)
        {
            modbus_frame_ready = true;
        }

        HAL_UART_Receive_IT(huart, &rx_byte, 1);
    }
}

void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan)
{
    if (HAL_CAN_GetRxMessage(hcan, CAN_RX_FIFO0, &can_rx_header, can_rx_data) == HAL_OK)
    {
        uint16_t modbus_reg;
        if (can_mapping_reverse_lookup(can_rx_header.StdId, &modbus_reg))
        {
            uint16_t received_value = ((uint16_t)can_rx_data[0] << 8) | can_rx_data[1];

            uint8_t response_buf[16];
            uint16_t response_len = modbus_build_read_response(1, &received_value, 1, response_buf);

            HAL_GPIO_WritePin(RS485_DE_GPIO_Port, RS485_DE_Pin, GPIO_PIN_SET);
            HAL_UART_Transmit(&huart2, response_buf, response_len, 100);
            HAL_GPIO_WritePin(RS485_DE_GPIO_Port, RS485_DE_Pin, GPIO_PIN_RESET);
        }
    }
}
